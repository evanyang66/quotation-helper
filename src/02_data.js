/* 行工厂：qty 数量 / price 单价 / amt 直接指定总价 / gift 赠送 / optional 选配
   type: 'item' 明细 | 'group' 分组标题 | 'subtotal' 小计 */
function R(item, desc, loc, qty, unit, price, opt, amt, gift) {
  return {
    item: item || "", desc: desc || "", loc: loc || "",
    qty: (qty === undefined || qty === null) ? "" : qty,
    unit: unit || "", price: (price === undefined || price === null) ? "" : price,
    amt: (amt === undefined || amt === null) ? "" : amt,
    optional: !!opt, gift: !!gift, type: "item"
  };
}
/* 分组标题行（跨列合并的粗体标题，如「一期明细」「附表1 门禁」） */
function G(title) { var r = R(); r.type = "group"; r.item = title || ""; return r; }
/* 小计行：金额自动汇总自上一个分组/小计之后的所有明细 */
function S(label) { var r = R(); r.type = "subtotal"; r.desc = label || "小计"; return r; }

